  /* Tono estable (0-359) a partir de un texto: cada cliente conserva su color. */
  function hueFor(text){
    let h = 0;
    const str = String(text || '');
    for(let i = 0; i < str.length; i++){ h = (h * 31 + str.charCodeAt(i)) % 360; }
    return h;
  }

